const SUPPORTED_YEARS = new Set(Object.keys(HOLIDAYS_KR).map((k) => k.slice(0, 4)));
const warnedYears = new Set<string>();

/** KST 달력 기준으로 공휴일인지. 데이터에 없는 연도는 false(개발 모드에서만 경고). */
export function isHoliday(date: Date): boolean {
  const key = formatKstDateKey(date);
  const year = key.slice(0, 4);
  if (!SUPPORTED_YEARS.has(year)) {
    if (process.env.NODE_ENV === "development" && !warnedYears.has(year)) {
      warnedYears.add(year);
      console.warn(`[holidays-kr] ${year}년 공휴일 데이터가 없습니다. src/lib/holidays-kr.ts에 추가하세요.`);
    }
    return false;
  }
  return key in HOLIDAYS_KR;
}
